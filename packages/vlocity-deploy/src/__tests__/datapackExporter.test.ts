    function createLogger() {
        const logger = {
            debug: jest.fn(),
            error: jest.fn(),
            info: jest.fn(),
            verbose: jest.fn(),
            warn: jest.fn(),
            distinct: jest.fn()
        };
        logger.distinct.mockReturnValue(logger);
        return logger;
    }

    function mockMatchingKeyService(fields: string[] = [ 'Name' ]) {
        return {
            getMatchingKey: jest.fn(async (type: string) => ({ sobjectType: type, fields, returnField: 'Id' }))
        };
    }

    function findDescribeField(describe: any, fieldName: string) {
        return describe?.fields?.find((field: any) => field.name === fieldName) ?? {
            name: fieldName,
            referenceTo: []
        };
    }

    function createExporter(options?: {
        matchingKeyFields?: string[];
        matchingKeyFieldsByType?: Record<string, string[]>;
        describe?: any;
        describes?: Record<string, any>;
        records?: Array<Record<string, any>>;
        autoGeneratedObjects?: string[];
        embeddedObjects?: (item: any) => any[];
    }) {
        const records = new Map((options?.records ?? []).map(record => [record.Id, { id: record.Id, ...record }]));
        const autoGeneratedObjects = new Set(options?.autoGeneratedObjects ?? []);
        const describeFor = (type?: string) => type ? options?.describes?.[type] ?? options?.describe : options?.describe;
        const definitions = {
            getEmbeddedObjects: jest.fn((item: any) => options?.embeddedObjects?.(item) ?? []),
            getDatapackTypes: jest.fn(() => []),
            getFieldsWith: jest.fn(() => []),
            isEmbeddedObject: jest.fn(() => false),
            isFieldIgnored: jest.fn(() => false)
        };
        const salesforce = {
            data: {
                cache: {
                    configure: jest.fn()
                },
                lookup: jest.fn(async (objectType: string, filter: Record<string, any>) =>
                    [...records.values()].filter(record =>
                        record.__type === objectType &&
                        Object.entries(filter ?? {}).every(([field, value]) => record[field] === value)
                    )
                ),
                lookupById: jest.fn(async (ids: string | string[]) =>
                    Array.isArray(ids)
                        ? new Map(ids.map(id => [id, records.get(id)]))
                        : records.get(ids)),
                lookupMultiple: jest.fn(async (objectType: string, filters: Record<string, any>[]) =>
                    filters.map(filter => [...records.values()].filter(record =>
                        record.__type === objectType &&
                        Object.entries(filter ?? {}).every(([field, value]) => record[field] === value)
                    )))
            },
            schema: {
                describeSObjectById: jest.fn(async (id: string) => describeFor(records.get(id)?.__type)),
                describeSObjectField: jest.fn(async (type: string, fieldName: string) =>
                    findDescribeField(describeFor(type), fieldName))
            },
            replaceNamespace: jest.fn((value: string) => value),
            updateNamespace: jest.fn((value: string) => value)
        };
        const matchingKeys = {
            getMatchingKey: jest.fn(async (type: string) => ({
                sobjectType: type,
                fields: autoGeneratedObjects.has(type)
                    ? []
                    : options?.matchingKeyFieldsByType?.[type] ?? options?.matchingKeyFields ?? (options?.records ? ['Name'] : []),
                returnField: 'Id'
            }))
        };

        const expander = {
            expandDatapack: jest.fn()
        };

        return {
            exporter: new DatapackExporter(
                definitions as any,
                expander as any,
                salesforce as any,
                salesforce.data as any,
                matchingKeys as any,
                createLogger() as any
            ) as any,
            expander,
            definitions,
            salesforce,
            matchingKeys
        };
    }

